"""Knowledge base rendering and stats: pure, no Obsidian needed."""

import re

import yaml

from obsidian_brain.knowledge import (
    KNOWLEDGE_BASE_PATH,
    compute_stats,
    knowledge_base_status,
    render_knowledge_base,
)
from obsidian_brain.memory import split_frontmatter

from .fake_vault import FakeVault

CREATED = "2026-01-02T03:04:05Z"
NOW = "2026-11-23T03:24:12Z"

VAULT = {
    "Home.md": "# Home\n\n[[Alpha]] and [[Beta]] #index",
    "Projects/Alpha.md": "# Alpha\n\n[[Beta]] #project/alpha",
    "Projects/Beta.md": "# Beta\n\n[[Home]] [[Missing]] [[Beta]]",
    "Lonely.md": "# Lonely, no links #Index",
    "Assets/pic.png": "binary",
}


async def render(files: dict[str, str], folders: list[str] | None = None, **kw: bool) -> str:
    snapshot = await FakeVault(files, folders).snapshot()
    return render_knowledge_base(snapshot, created=CREATED, now=NOW, **kw)


def frontmatter_of(text: str) -> dict[str, object]:
    return yaml.safe_load(split_frontmatter(text)[0].strip().strip("-"))  # type: ignore[no-any-return]


async def test_stats_count_recursive_folders_and_note_to_note_links() -> None:
    files = {**VAULT, "a/b/c/d.md": "x"}
    stats = compute_stats(await FakeVault(files, ["x/y/z"]).snapshot())
    assert stats.total_folders == 8  # Projects, Assets, a, a/b, a/b/c, x, x/y, x/y/z
    assert stats.total_notes == 5
    # Home->Alpha, Home->Beta, Alpha->Beta, Beta->Home; the unresolved and self links are ignored.
    assert stats.total_links == 4
    assert stats.orphan_notes == 2  # Lonely and a/b/c/d
    assert stats.total_tags == 2  # 'index' (merged with 'Index') and 'project/alpha'


async def test_generated_files_are_not_notes_orphans_or_folders() -> None:
    files = {
        **VAULT,
        "Obsidian Brain/config.md": "```yaml\na: 1\n```",
        KNOWLEDGE_BASE_PATH: "---\ncreated: x\n---\n# old",
        "Obsidian Brain/memories/m.md": "#memtag",
    }
    stats = compute_stats(await FakeVault(files).snapshot())
    assert (stats.total_notes, stats.total_folders, stats.orphan_notes) == (4, 2, 1)
    text = await render(files)
    assert "Obsidian Brain" not in text.split("## Folder Structure")[1].split("## Tag")[0]
    assert "memtag" not in text
    assert "Obsidian Brain/config.md" not in text and "knowledge-base.md" not in text


async def test_timestamps_are_utc_and_created_is_carried_over() -> None:
    text = await render(VAULT)
    meta = frontmatter_of(text)
    assert meta["created"] == CREATED and meta["updated"] == NOW
    assert text.rstrip().endswith(f"*Generated by Obsidian Brain MCP on {NOW}*")
    assert meta["generator"] == "obsidian-brain-mcp"
    assert re.fullmatch(r"\d{4}-\d\d-\d\dT\d\d:\d\d:\d\dZ", str(meta["updated"]))


async def test_pipes_in_cells_are_escaped() -> None:
    files = {"Edge/Pipes | in | name.md": "[[Other]]", "Other.md": "[[Edge/x]]"}
    text = await render(files)
    rows = [line for line in text.splitlines() if "Pipes" in line and line.startswith("|")]
    assert rows
    for row in rows:
        cells = re.split(r"(?<!\\)\|", row.strip().strip("|"))
        assert len(cells) == 4, row  # Note, Incoming, Outgoing, Total
        assert "Pipes \\| in \\| name.md" in cells[0]


async def test_folder_tree_nests_every_level() -> None:
    text = await render({"a/b/c/n.md": "x", "z/n.md": "x"}, ["a/e"])
    tree = text.split("```")[1]
    assert tree == "\n/\n├── a/\n│   ├── b/\n│   │   └── c/\n│   └── e/\n└── z/\n"


async def test_tag_table_and_hierarchy() -> None:
    text = await render(VAULT)
    assert "| 1 | #index | 2 | Home.md |" in text
    assert "- **#project**\n  - #project/alpha (1)" in text


async def test_hubs_links_and_orphans_sections() -> None:
    text = await render(VAULT)
    assert "| Home.md | 1 | 2 | 3 |" in text
    assert "1. **Projects/Beta.md** (2 backlinks)" in text
    assert "- `Lonely.md`" in text
    assert "Notes with no links to or from other notes (1 total)" in text


async def test_optional_sections_can_be_left_out() -> None:
    text = await render(VAULT, include_orphans=False, include_link_patterns=False)
    assert "## Orphan Notes" not in text and "## Link Patterns" not in text
    assert "## Hub Notes" in text


async def test_empty_vault_renders() -> None:
    text = await render({})
    assert "*No tags found in vault.*" in text and "*No connected notes found.*" in text
    assert "| Notes | 0 |" in text


async def test_orphan_list_is_capped() -> None:
    text = await render({f"n{i:02d}.md": "x" for i in range(25)})
    assert "(25 total)" in text and "*...and 5 more*" in text


def test_status_reads_the_frontmatter_of_the_file() -> None:
    assert knowledge_base_status(None).exists is False
    status = knowledge_base_status(
        {
            "created": CREATED,
            "updated": NOW,
            "vault_stats": {
                "total_notes": 1,
                "total_folders": 0,
                "total_tags": 0,
                "total_links": 0,
                "orphan_notes": 1,
            },
        }
    )
    assert (status.exists, status.created, status.updated) == (True, CREATED, NOW)
    assert status.stats and status.stats.total_notes == 1
    assert knowledge_base_status({"vault_stats": "garbage"}).stats is None
